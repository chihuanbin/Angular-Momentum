def make_robustness_figure(
    bootstrap: pd.DataFrame,
    selection: pd.DataFrame,
    age_mc: pd.DataFrame,
    residuals: pd.DataFrame,
    outdir: Path,
) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(10.5, 8.0), constrained_layout=True)

    ax = axes[0, 0]
    ok_boot = bootstrap["status"].eq("ok") & np.isfinite(bootstrap["break_age_Myr"])
    ax.hist(bootstrap.loc[ok_boot, "break_age_Myr"], bins=30, color="darkorange", alpha=0.82)
    ax.set_xlabel(r"Bootstrap $t_b$ (Myr)")
    ax.set_ylabel("Resamples")

    ax = axes[0, 1]
    ok_sel = selection["status"].eq("ok")
    y = np.arange(ok_sel.sum())
    rows = selection.loc[ok_sel].sort_values("break_age_Myr")
    ax.errorbar(rows["break_age_Myr"], y, fmt="o", color="steelblue")
    ax.set_yticks(y)
    ax.set_yticklabels(rows["test"], fontsize=8)
    ax.set_xlabel(r"Selection-test $t_b$ (Myr)")

    ax = axes[1, 0]
    ok_age = age_mc["status"].eq("ok") & np.isfinite(age_mc["break_age_Myr"])
    labels = list(dict.fromkeys(age_mc.loc[ok_age, "test"].astype(str)))
    data = [age_mc.loc[ok_age & age_mc["test"].eq(label), "break_age_Myr"].to_numpy(float) for label in labels]
    ax.boxplot(data, tick_labels=[label.replace("assumed_sigma_logage_", "sig=") for label in labels], vert=True)
    ax.tick_params(axis="x", rotation=35, labelsize=8)
    ax.set_ylabel(r"Age-MC $t_b$ (Myr)")

    ax = axes[1, 1]
    rows = residuals.head(8)
    ax.barh(np.arange(len(rows)), rows["spearman_rho"], color="0.45")
    ax.set_yticks(np.arange(len(rows)))
    ax.set_yticklabels(rows["property"], fontsize=8)
    ax.axvline(0.0, color="black", lw=1.0)
    ax.set_xlabel("Residual Spearman rho")
    ax.invert_yaxis()

    fig.savefig(outdir / "figure_robustness_checks.png", dpi=240)
    plt.close(fig)


def write_summary(
    selection: pd.DataFrame,
    bootstrap: pd.DataFrame,
    jackknife: pd.DataFrame,
    age_mc: pd.DataFrame,
    residuals: pd.DataFrame,
    nulls: pd.DataFrame,
    systematics: pd.DataFrame,
    bootstrap_selection: pd.DataFrame,
    outdir: Path,
) -> None:
    boot_ok = bootstrap["status"].eq("ok") & np.isfinite(bootstrap["break_age_Myr"])
    boot_tb = bootstrap.loc[boot_ok, "break_age_Myr"].to_numpy(float)
    jack_ok = jackknife["status"].eq("ok") & np.isfinite(jackknife["break_age_Myr"])
    jack_tb = jackknife.loc[jack_ok, "break_age_Myr"].to_numpy(float)
    age_ok = age_mc["status"].eq("ok") & np.isfinite(age_mc["break_age_Myr"])

    lines = [
        "# Robustness Checks",
        "",
        "## Bootstrap",
        "",
        f"Successful resamples: {len(boot_tb)} / {len(bootstrap)}",
        f"t_b median and 16-84% interval: {np.nanmedian(boot_tb):.2f} ({np.nanpercentile(boot_tb, 16):.2f}-{np.nanpercentile(boot_tb, 84):.2f}) Myr",
        f"Broken model preferred by BIC: {100.0 * bootstrap_selection['broken_preferred_fraction'].iloc[0]:.1f}%",
        f"Broken model strongly preferred (Delta BIC < -6): {100.0 * bootstrap_selection['broken_delta_bic_lt_minus6_fraction'].iloc[0]:.1f}%",
        "",
        "## Leave-one-out jackknife",
        "",
        f"Successful leave-one-out fits: {len(jack_tb)} / {len(jackknife)}",
        f"t_b range: {np.nanmin(jack_tb):.2f}-{np.nanmax(jack_tb):.2f} Myr",
        "",
        "## Selection tests",
        "",
    ]
    for row in selection.itertuples():
        lines.append(
            f"- {row.test}: n={row.n}, t_b={row.break_age_Myr:.2f} Myr, Delta BIC={row.delta_bic_vs_single:.2f}, status={row.status}"
        )
    lines.extend(["", "## Age uncertainty tests", ""])
    for label, sub in age_mc.loc[age_ok].groupby("test"):
        values = sub["break_age_Myr"].to_numpy(float)
        delta = sub["delta_bic_vs_single"].to_numpy(float)
        lines.append(
            f"- {label}: t_b={np.nanmedian(values):.2f} ({np.nanpercentile(values, 16):.2f}-{np.nanpercentile(values, 84):.2f}) Myr; "
            f"Delta BIC={np.nanmedian(delta):.2f}"
        )
    lines.extend(["", "## Residual diagnostics", ""])
    for row in residuals.head(6).itertuples():
        lines.append(f"- {row.property}: rho={row.spearman_rho:.3f}, p={row.p_value:.3g}, n={row.n}")
    lines.extend(["", "## Null-shuffle diagnostics", ""])
    if nulls.empty:
        lines.append("- No f_L_null_p column available.")
    else:
        for row in nulls.itertuples():
            lines.append(
                f"- {row.metric}: n={row.n}, median p_null={row.median_null_p:.3f}, "
                f"p<0.05 fraction={row.false_positive_fraction_p_lt_0p05:.3f}"
            )
    lines.extend(["", "## Systematics amplitude checks", ""])
    if systematics.empty:
        lines.append("- No amplitude checks available from current tables.")
    else:
        for row in systematics.itertuples():
            lines.append(
                f"- {row.systematic}: amplitude={row.amplitude_Myr_inv:.4g} Myr^-1, "
                f"median amplitude/omega={row.median_amplitude_over_omega:.3f}; {row.comment}"
            )
    (outdir / "summary.md").write_text("\n".join(lines) + "\n")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--population", type=Path, default=Path("outputs_v3/cluster_population.csv"))
    parser.add_argument("--sample", type=Path, default=Path("outputs/sample_selection.csv"))
    parser.add_argument("--outdir", type=Path, default=Path("outputs_robustness"))
    parser.add_argument("--bootstrap", type=int, default=300)
    parser.add_argument("--age-mc", type=int, default=80)
    parser.add_argument("--seed", type=int, default=20260624)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.outdir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(args.seed)

    df = valid_population(pd.read_csv(args.population))
    if args.sample.exists():
        sample = pd.read_csv(args.sample)
        sample_cols = ["ID", "dist50", "RV", "logAge16", "logAge84"]
        df = df.merge(sample[[col for col in sample_cols if col in sample.columns]], on="ID", how="left")

    comparison, _ = model_comparison_v3(df)
    selection = selection_tests(df)
    clean = df[df.get("p_good_v3", pd.Series(1.0, index=df.index)) > 0.7].copy().reset_index(drop=True)
    bootstrap = bootstrap_breaks(clean, args.bootstrap, rng)
    bootstrap_selection = bootstrap_model_selection_summary(bootstrap)
    jackknife = jackknife_breaks(clean)
    age_mc = age_uncertainty_tests(clean, [0.05, 0.10, 0.15, 0.20], args.age_mc, rng)
    residuals = residual_diagnostics(clean)
    nulls = null_shuffle_summary(df)
    systematics = systematics_amplitudes(df)
    naive_vs_conservative = naive_vs_conservative_table(
        Path("outputs_v3_debug/model_comparison.csv"), comparison, selection, bootstrap_selection
    )
    budget = systematics_budget_table(selection, age_mc, residuals, nulls, systematics)

    comparison.to_csv(args.outdir / "intrinsic_scatter_model_comparison.csv", index=False)
    selection.to_csv(args.outdir / "selection_robustness.csv", index=False)
    bootstrap.to_csv(args.outdir / "bootstrap_breaks.csv", index=False)
    bootstrap_selection.to_csv(args.outdir / "bootstrap_model_selection_summary.csv", index=False)
    jackknife.to_csv(args.outdir / "jackknife_breaks.csv", index=False)
    age_mc.to_csv(args.outdir / "age_uncertainty_mc.csv", index=False)
    residuals.to_csv(args.outdir / "residual_diagnostics.csv", index=False)
    nulls.to_csv(args.outdir / "null_shuffle_summary.csv", index=False)
    systematics.to_csv(args.outdir / "systematics_amplitudes.csv", index=False)
    naive_vs_conservative.to_csv(args.outdir / "naive_vs_conservative.csv", index=False)
    budget.to_csv(args.outdir / "systematics_budget.csv", index=False)

    make_robustness_figure(bootstrap, selection, age_mc, residuals, args.outdir)
    write_summary(selection, bootstrap, jackknife, age_mc, residuals, nulls, systematics, bootstrap_selection, args.outdir)

    broken = comparison.loc[comparison["model"] == "broken"].iloc[0]
    boot_ok = bootstrap["status"].eq("ok") & np.isfinite(bootstrap["break_age_Myr"])
    print(f"Intrinsic-scatter broken Delta BIC vs single: {broken['delta_bic_vs_single']:.3f}")
    print(f"Intrinsic-scatter broken break: {broken['break_age_Myr']:.2f} Myr")
    print(f"Clean-sample bootstrap successes: {int(boot_ok.sum())}/{len(bootstrap)}")
    print(f"Wrote outputs to {args.outdir}")


if __name__ == "__main__":
    main()
