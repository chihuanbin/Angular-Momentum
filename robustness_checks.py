#!/usr/bin/env python3
"""Robustness checks for the Gaia DR3 open-cluster population break.

This script consumes the reproducible tables already generated by
``fossil_angular_momentum.py`` and ``scheme_v3_analysis.py``.  It does not
invent new kinematic measurements; all tests refit the population models after
resampling or filtering existing fitted clusters.
"""

